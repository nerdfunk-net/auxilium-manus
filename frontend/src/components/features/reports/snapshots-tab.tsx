"use client";

import { Eye, Loader2, Trash2 } from "lucide-react";
import { useCallback, useState } from "react";

import { Alert, AlertDescription } from "@/components/ui/alert";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import { TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import { useReportSnapshotMutations } from "@/hooks/queries/use-report-snapshot-mutations";
import { useReportSnapshotsQuery } from "@/hooks/queries/use-report-snapshots-query";
import { useAuthStore } from "@/lib/auth-store";
import { hasPermission } from "@/lib/permissions";

import { SnapshotViewer } from "./components/snapshot-viewer";
import type { ReportSnapshotSummary } from "./types/report-definition";
import { formatTimestamp } from "./utils/format";

/** Stored report snapshots, newest first. */
export function SnapshotsTab() {
  const canDelete = hasPermission(useAuthStore((state) => state.user), "reports", "delete");
  const list = useReportSnapshotsQuery();
  const { deleteSnapshot } = useReportSnapshotMutations();
  const [viewing, setViewing] = useState<number | null>(null);
  const [toDelete, setToDelete] = useState<ReportSnapshotSummary | null>(null);

  const handleConfirmDelete = useCallback(() => {
    if (!toDelete) return;
    deleteSnapshot.mutate(toDelete.id, { onSettled: () => setToDelete(null) });
  }, [deleteSnapshot, toDelete]);

  if (list.isLoading) {
    return (
      <div className="flex justify-center py-12">
        <Loader2 className="size-5 animate-spin text-muted-foreground" />
      </div>
    );
  }
  if (list.isError) {
    return (
      <Alert variant="destructive">
        <AlertDescription>{list.error.message}</AlertDescription>
      </Alert>
    );
  }

  const snapshots = list.data ?? [];
  return (
    <div className="space-y-3">
      <p className="text-sm text-muted-foreground">
        A snapshot is a stored copy of a generated report. It does not change when the data does.
      </p>
      <div className="rounded-lg border">
        <table className="w-full caption-bottom text-sm">
          <TableHeader>
            <TableRow>
              <TableHead>Name</TableHead>
              <TableHead>Status</TableHead>
              <TableHead>Generated by</TableHead>
              <TableHead>Generated</TableHead>
              <TableHead className="w-24" />
            </TableRow>
          </TableHeader>
          <TableBody>
            {snapshots.length === 0 ? (
              <TableRow>
                <TableCell colSpan={5} className="py-8 text-center text-sm text-muted-foreground">
                  No snapshots yet. Generate a report on the Reports tab.
                </TableCell>
              </TableRow>
            ) : (
              snapshots.map((snapshot) => (
                <TableRow key={snapshot.id}>
                  <TableCell className="font-medium">{snapshot.name}</TableCell>
                  <TableCell>
                    <Badge variant={snapshot.status === "complete" ? "secondary" : "destructive"}>
                      {snapshot.status === "complete" ? "Complete" : "Partial"}
                    </Badge>
                  </TableCell>
                  <TableCell className="text-xs">{snapshot.generated_by ?? "-"}</TableCell>
                  <TableCell className="text-xs text-muted-foreground">
                    {formatTimestamp(snapshot.generated_at)}
                  </TableCell>
                  <TableCell>
                    <div className="flex justify-end gap-1">
                      <Button
                        size="icon"
                        variant="ghost"
                        aria-label={`View ${snapshot.name}`}
                        onClick={() => setViewing(snapshot.id)}
                      >
                        <Eye className="size-4" />
                      </Button>
                      {canDelete ? (
                        <Button
                          size="icon"
                          variant="ghost"
                          aria-label={`Delete ${snapshot.name}`}
                          onClick={() => setToDelete(snapshot)}
                        >
                          <Trash2 className="size-4" />
                        </Button>
                      ) : null}
                    </div>
                  </TableCell>
                </TableRow>
              ))
            )}
          </TableBody>
        </table>
      </div>

      <Dialog open={toDelete !== null} onOpenChange={(open) => (open ? undefined : setToDelete(null))}>
        <DialogContent>
          <DialogHeader>
            <DialogTitle>Delete snapshot?</DialogTitle>
            <DialogDescription>{toDelete ? `“${toDelete.name}” will be deleted for good.` : ""}</DialogDescription>
          </DialogHeader>
          <DialogFooter>
            <Button variant="outline" onClick={() => setToDelete(null)}>
              Cancel
            </Button>
            <Button variant="destructive" onClick={handleConfirmDelete} disabled={deleteSnapshot.isPending}>
              Delete
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>

      <SnapshotViewer snapshotId={viewing} onClose={() => setViewing(null)} />
    </div>
  );
}
